// Rebuilds the symbol library's sprite.svg and contact sheet (index.html), and src/symbols.js, the
// copy of the library the app embeds (ids, labels, category, abbreviation, drawing).
// Run from the repo root: node tools/build-symbols.js
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..'), dir = path.join(root, 'symbols');
const man = JSON.parse(fs.readFileSync(path.join(dir, 'manifest.json'), 'utf8'));
const esc = s => String(s).replace(/[&<>"]/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));
const inner = id => {
  const s = fs.readFileSync(path.join(dir, 'svg', id + '.svg'), 'utf8').replace(/<metadata>[\s\S]*?<\/metadata>/g, '');
  const m = /<\/title>([\s\S]*)<\/svg>\s*$/.exec(s);
  if (!m) throw new Error('unexpected SVG layout: ' + id);
  return m[1].trim();
};
const syms = man.symbols.map(s => ({ ...s, body: inner(s.id) }));

fs.writeFileSync(path.join(dir, 'sprite.svg'), `<svg xmlns="http://www.w3.org/2000/svg" style="display:none">\n` +
  syms.map(s => `<symbol id="tb-${s.id}" viewBox="0 0 64 64"><title>${esc(s.label_en)}</title>${s.body}</symbol>`).join('\n') + '\n</svg>\n');

const cats = Object.keys(man.categories);
fs.writeFileSync(path.join(dir, 'index.html'), `<!DOCTYPE html><html><head><meta charset="utf-8"><title>TrailBlazing roadbook symbols</title><style>body{font:12px Arial;margin:16px}h3{margin:18px 0 6px}.g{display:grid;grid-template-columns:repeat(9,1fr);gap:8px}.c{border:1px solid #ccc;padding:6px;text-align:center}.c.new{border-color:#e8590c}.c img{width:56px;height:56px;display:block;margin:0 auto 4px}.c b{display:block;font-size:11px}.c span{color:#666;font-size:10px}</style></head><body>` +
  `<h2>TrailBlazing roadbook symbols v${man.version} (${syms.length})</h2><p>Orange border: added in v1.1.0.</p>` +
  cats.map(c => `<h3>${esc(c)} <span style="font-weight:normal;color:#666">${esc(man.categories[c])}</span></h3><div class="g">` +
    syms.filter(s => s.category === c).map(s => `<div class="c${s.since ? ' new' : ''}"><img src="svg/${s.id}.svg"><b>${s.id}</b><span>${esc(s.label_en)}</span></div>`).join('') + '</div>').join('') +
  '</body></html>\n');

const app = syms.map(s => ({ id: s.id, fr: s.label_fr, en: s.label_en, cat: s.category, abbr: s.abbr || null, svg: s.body }));
fs.writeFileSync(path.join(root, 'src', 'symbols.js'), `"use strict";\n// Generated by tools/build-symbols.js from symbols/manifest.json (library v${man.version}). Do not edit.\n` +
  `const TB_SYMBOLS = ${JSON.stringify(app)};\nconst TB_SYM = new Map(TB_SYMBOLS.map(s => [s.id, s]));\n` +
  `function tbSymSVG(id, size = 20) { const s = TB_SYM.get(id); return s ? \`<svg viewBox="0 0 64 64" width="\${size}" height="\${size}" class="tbsym"><title>\${esc(s.en)}</title>\${s.svg}</svg>\` : ''; }\n`);
console.log('symbols:', syms.length);
